// Tests for scripts/check-conflict-markers.js using a throwaway git repository.
const fs = require("fs"), path = require("path"), os = require("os");
const { execFileSync, spawnSync } = require("child_process");
const { scan } = require("./check-conflict-markers");
let fail = 0;
const t = (n, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fail++; console.log(`${ok ? "PASS" : "FAIL"} ${n}${ok ? "" : ` (got ${JSON.stringify(got)}, want ${JSON.stringify(want)})`}`); };
const root = fs.mkdtempSync(path.join(os.tmpdir(), "aisdlc-cm-"));
const g = (...a) => execFileSync("git", ["-C", root, ...a], { stdio: "pipe" });
const put = (rel, data) => fs.writeFileSync(path.join(root, rel), data);
g("init", "-q");
put("clean.md", "# title\n=======\nunderline-style heading above is fine\n");
put("a.js", "ok\n<<<<<<< HEAD\nx\n=======\ny\n>>>>>>> origin/main\n");
put("crlf.txt", "<<<<<<< HEAD\r\nz\r\n");
put("indented.md", "    <<<<<<< HEAD (indented, e.g. a quoted example)\n");
put("eight.md", "<<<<<<<<< not a marker\n");
put("bin.dat", Buffer.from([0, 1, 2, 60, 60, 60, 60, 60, 60, 60, 32]));
put("untracked.js", "<<<<<<< HEAD\n");
g("add", "clean.md", "a.js", "crlf.txt", "indented.md", "eight.md", "bin.dat");
const hits = scan(root).map((h) => h.split(":").slice(0, 2).join(":"));
t("finds both markers in a.js", hits.filter((h) => h.startsWith("a.js")), ["a.js:2", "a.js:6"]);
t("finds CRLF file", hits.includes("crlf.txt:1"), true);
t("ignores a setext underline", hits.some((h) => h.startsWith("clean.md")), false);
t("ignores indented and 8+ char lines", hits.some((h) => h.startsWith("indented.md") || h.startsWith("eight.md")), false);
t("ignores binary", hits.some((h) => h.startsWith("bin.dat")), false);
t("ignores untracked files", hits.some((h) => h.startsWith("untracked.js")), false);
const cli = path.join(__dirname, "check-conflict-markers.js");
const bad = spawnSync("node", [cli, "--root", root], { encoding: "utf8" });
t("cli exits 1 and names the file", [bad.status, /a\.js:2/.test(bad.stderr)], [1, true]);
g("rm", "-q", "--cached", "a.js", "crlf.txt");
t("clean tree passes", scan(root), []);
const ok = spawnSync("node", [cli, "--root", root], { encoding: "utf8" });
t("cli exits 0 when clean", [ok.status, /no conflict markers/.test(ok.stdout)], [0, true]);
const here = spawnSync("node", [cli], { encoding: "utf8" });
t("this repository is clean", here.status, 0);
fs.rmSync(root, { recursive: true, force: true });
process.exit(fail ? 1 : 0);
